#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""Select and stage the files Vercel may serve.

Vercel used to publish the repository root, so build scripts, review tooling,
CI configuration, internal documents, build data and the build's own
__pycache__ were all downloadable from production. The build still needs the
whole checkout (it runs the Python pipeline), so `.vercelignore` cannot remove
them. Instead the last build step copies only the public site into `dist/`,
and vercel.json serves that directory. Functions (api/) and middleware.js are
still deployed from the project root as before; they are not static files.

Selection is an allowlist shared with the local server (_serve.mjs): a root
file is public only when listed (or an IndexNow key file), a directory only
when listed in PUBLIC_DIRS, and no '_'/'.'-prefixed or tooling file is ever
served. _check_deploy_exposure.py requires every tracked path to be
classified, so a new site directory or root page fails the quality gate
instead of silently disappearing from production.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import sys
from pathlib import Path, PurePosixPath


ROOT = Path(__file__).resolve().parent
OUTPUT = 'dist'

# The same public site the local server (_serve.mjs) exposes; the audit keeps
# both lists identical. pagefind/ is generated by the build.
PUBLIC_DIRS = frozenset({'.well-known', 'admin', 'ai', 'assets', 'blog', 'en', 'exam', 'pagefind'})
PUBLIC_ROOT_FILES = frozenset({
    '404.html', 'about.html', 'admin.html', 'dashboard.html', 'glossary.html', 'index.html',
    'notes.html', 'offline.html', 'privacy.html', 'reset-sw.html', 'support.html', 'tools.html',
    'ads.txt', 'humans.txt', 'llms.txt', 'llms-full.txt', 'robots.txt', 'sitemap.xml',
    'manifest.json', 'opensearch.xml', 'sw.js', 'favicon.ico', 'apple-touch-icon.png', 'icon.svg',
    'icon-16.png', 'icon-32.png', 'icon-48.png', 'icon-64.png', 'icon-96.png', 'icon-128.png',
    'icon-180.png', 'icon-192.png', 'icon-256.png', 'icon-512.png', 'logo-512.png',
})
# IndexNow / site-verification files at the root contain only their own key.
VERIFICATION_FILE = re.compile(r'[A-Za-z0-9-]{8,128}\.txt')
# Never served, even inside a public directory.
PRIVATE_SUFFIXES = frozenset({'.py', '.pyc', '.md', '.cjs', '.mjs', '.ts', '.ps1', '.bat', '.sh',
                              '.yml', '.yaml', '.ini', '.log', '.frag', '.pem', '.key'})
PRIVATE_PARTS = frozenset({'__pycache__', 'node_modules'})
# Never part of the site or the repository: VCS data, build output, local review/CI evidence.
LOCAL_ARTIFACT_DIRS = frozenset({'.git', OUTPUT, '.vercel', '.codex-review', '.claude-review', '.lighthouseci',
                                 'delivery-preview'})
CREDENTIAL_NAME = re.compile(r'(?:service-account|credentials|firebase-adminsdk|gcloud-key|positive-guild-).*\.json',
                             re.IGNORECASE)


def is_verification_file(root: Path, name: str) -> bool:
    path = Path(root) / name
    if not VERIFICATION_FILE.fullmatch(name) or _linked(path) or not path.is_file() or path.stat().st_size > 130:
        return False
    return path.read_text(encoding='utf-8', errors='replace').strip() == name[:-4]


def is_published(relative: str, root: Path = ROOT) -> bool:
    """Whether a POSIX path relative to the project root may be served."""
    path = PurePosixPath(relative)
    parts = path.parts
    if not parts or path.is_absolute() or '..' in parts:
        return False
    if any(part in PRIVATE_PARTS or part.startswith('_') or CREDENTIAL_NAME.search(part) for part in parts):
        return False
    if path.suffix.lower() in PRIVATE_SUFFIXES:
        return False
    if any(part.startswith('.') and (index or part != '.well-known') for index, part in enumerate(parts)):
        return False
    if len(parts) == 1:
        return parts[0] in PUBLIC_ROOT_FILES or is_verification_file(root, parts[0])
    return parts[0] in PUBLIC_DIRS


def _linked(path: Path) -> bool:
    return path.is_symlink() or getattr(path, 'is_junction', lambda: False)()


def published_files(root: Path = ROOT) -> list[str]:
    """Every regular file under root that the deployment may serve."""
    root = Path(root).resolve()
    found = []
    for top in sorted(root.iterdir()):
        if top.name == OUTPUT or top.name in PRIVATE_PARTS:
            continue
        if top.is_file() and not _linked(top):
            if is_published(top.name, root):
                found.append(top.name)
            continue
        if top.name not in PUBLIC_DIRS or not top.is_dir():
            continue
        if _linked(top):
            raise ValueError(f'Linked public directory: {top.name}')
        for directory, dirnames, filenames in os.walk(top):
            here = Path(directory)
            for name in list(dirnames):
                if _linked(here / name):
                    raise ValueError(f'Linked directory inside the site: {(here / name).relative_to(root).as_posix()}')
            dirnames[:] = sorted(name for name in dirnames if name not in PRIVATE_PARTS)
            for name in sorted(filenames):
                path = here / name
                relative = path.relative_to(root).as_posix()
                if _linked(path) or not path.is_file():
                    raise ValueError(f'Site file is not an ordinary file: {relative}')
                if is_published(relative, root):
                    found.append(relative)
    return sorted(found)


def stage(root: Path, output: Path) -> list[str]:
    """Copy the published files into a fresh output directory and verify the copy."""
    root, output = Path(root).resolve(), Path(output)
    if output.exists() or _linked(output):
        if _linked(output) or not output.is_dir():
            raise ValueError('Refusing to replace a linked or non-directory output')
        shutil.rmtree(output)
    files = published_files(root)
    for relative in files:
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / relative, target)
    copied = sorted(path.relative_to(output).as_posix() for path in output.rglob('*') if path.is_file())
    if copied != files:
        raise ValueError('Staged site does not match the published file selection')
    return files


GENERATED_DIR = 'pagefind'  # built on Vercel by `npm run build:deploy`, never part of the checkout


def census(output: Path) -> str:
    """One build-log line describing exactly what the output directory holds.

    The Preview check reads it back through the Vercel deployment events API
    for the exact-SHA deployment (the API lists no output files for Git
    deployments) and compares it with the checkout's public selection: the
    sha256 covers the sorted list of every non-generated file, so a missing,
    extra or internal file changes it.
    """
    output = Path(output)
    names = sorted(path.relative_to(output).as_posix() for path in output.rglob('*') if path.is_file())
    tracked = [name for name in names if not name.startswith(GENERATED_DIR + '/')]
    digest = hashlib.sha256('\n'.join(tracked).encode('utf-8')).hexdigest()
    search = int(f'{GENERATED_DIR}/pagefind.js' in names)
    return f'[site-census] files={len(tracked)} sha256={digest} generated={len(names) - len(tracked)} search={search}'


def checkout_manifest(root: Path = ROOT) -> dict[str, list[str]]:
    """Checkout files split into served and never-served paths (for live probes).

    Walks the filesystem instead of asking git: the Preview job runs in a
    container where git rejects the runner-owned checkout. In that fresh
    checkout the files are exactly the tracked files.
    """
    root = Path(root).resolve()
    names = []
    for directory, dirnames, filenames in os.walk(root):
        here = Path(directory)
        dirnames[:] = sorted(name for name in dirnames if name not in PRIVATE_PARTS
                             and not (here == root and name in LOCAL_ARTIFACT_DIRS))
        names += [(here / name).relative_to(root).as_posix() for name in filenames]
    names.sort()
    return {'published': [name for name in names if is_published(name, root)],
            'private': [name for name in names if not is_published(name, root)]}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--stage', metavar='DIR', help=f'stage the site into DIR (only {OUTPUT!r}, Vercel builds only)')
    action.add_argument('--manifest', action='store_true', help='print checkout served/private paths as JSON')
    args = parser.parse_args(argv)
    if args.manifest:
        print(json.dumps(checkout_manifest()))
        return 0
    if args.stage != OUTPUT:
        parser.error(f'the deployment output directory is {OUTPUT!r}')
    # A local copy would duplicate every page under the checkout for the
    # recursive auditors, so staging runs only inside a Vercel build.
    if os.environ.get('VERCEL_ENV') not in {'preview', 'production'}:
        print('[FAIL] Site staging runs only inside a Vercel build', file=sys.stderr)
        return 1
    files = stage(ROOT, ROOT / OUTPUT)
    print(f'[OK] Staged {len(files)} public files into {OUTPUT}/')
    print(census(ROOT / OUTPUT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
